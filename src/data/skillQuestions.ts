/** Passt zur Signatur von planQuickCheck(..., questionFor) in journeyFlow.ts.
 *  Gibt null zurueck, wenn es (noch) keine kuratierte Frage gibt — dann
 *  greift dort der Standard-Fallback. */
export function skillQuestionFor(skillId: string): { question: string; hint: string } | null {
  const question = SKILL_QUESTIONS[skillId];
  if (!question) return null;
  const knowing = /^(Kennst|Weißt|Kannst)\b/.test(question);
  return { question, hint: knowing ? HINT_KNOWING : HINT_DOING };
}